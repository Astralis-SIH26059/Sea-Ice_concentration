import xarray as xr
import matplotlib.pyplot as plt
import numpy as np


# ============================================================
# 1. FILE LOCATION
# ============================================================

file_path = "data/raw/sic_pss25_20150101-20151231_v06r00.nc"


# ============================================================
# 2. OPEN DATASET
# ============================================================

print("Opening NetCDF file...")

ds = xr.open_dataset(file_path)

print("File opened successfully!")


# ============================================================
# 3. GET SEA-ICE CONCENTRATION
# ============================================================

sic = ds["cdr_seaice_conc"]


# ============================================================
# 4. SELECT FIRST DAY
# ============================================================

first_day = sic.isel(time=0)

date = ds.time.values[0]

print("Date:", date)

print("Grid shape:", first_day.shape)


# ============================================================
# 5. GET ORIGINAL PROJECTED COORDINATES
# ============================================================

x = ds.x.values
y = ds.y.values


print("X range:", x.min(), "to", x.max())
print("Y range:", y.min(), "to", y.max())


# ============================================================
# 6. GET SEA-ICE VALUES
# ============================================================

ice = first_day.values


# ============================================================
# 7. MASK MISSING VALUES
# ============================================================

ice = np.ma.masked_invalid(ice)


# ============================================================
# 8. CREATE FIGURE
# ============================================================

plt.figure(figsize=(10, 10))


# ============================================================
# 9. PLOT USING NATIVE POLAR STEREOGRAPHIC GRID
# ============================================================

plt.pcolormesh(
    x,
    y,
    ice,
    shading="auto",
    vmin=0,
    vmax=1
)


# ============================================================
# 10. COLORBAR
# ============================================================

colorbar = plt.colorbar()

colorbar.set_label(
    "Sea Ice Concentration"
)


# ============================================================
# 11. TITLE
# ============================================================

plt.title(
    "Antarctic Sea Ice Concentration - 2015-01-01"
)


# ============================================================
# 12. AXIS LABELS
# ============================================================

plt.xlabel("Polar Stereographic X (meters)")

plt.ylabel("Polar Stereographic Y (meters)")


# ============================================================
# 13. KEEP EQUAL ASPECT RATIO
# ============================================================

plt.axis("equal")


# ============================================================
# 14. GRID
# ============================================================

plt.grid(True)


# ============================================================
# 15. SAVE IMAGE
# ============================================================

output_file = "antarctic_seaice_2015_01_01_native.png"

plt.savefig(
    output_file,
    dpi=200,
    bbox_inches="tight"
)


# ============================================================
# 16. SHOW
# ============================================================

plt.show()


print("\n====================================")
print("MAP CREATED SUCCESSFULLY!")
print("Saved as:", output_file)
print("====================================")